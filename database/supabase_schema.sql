-- Eliminar tablas anteriores si existen para reiniciar limpiamente
DROP TABLE IF EXISTS public.platos CASCADE;
DROP TABLE IF EXISTS public.municipios CASCADE;
DROP TABLE IF EXISTS public.configuracion_hero CASCADE;
DROP TABLE IF EXISTS public.administradores CASCADE;

-- 1. Tabla de Municipios (Limpia)
CREATE TABLE public.municipios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL UNIQUE,
  region VARCHAR(50) NOT NULL DEFAULT 'Valles Centrales',
  descripcion TEXT,
  imagen TEXT,
  descripcion_cultural TEXT,
  lugar_turistico_nombre VARCHAR(150),
  lugar_turistico_descripcion TEXT,
  lugar_turistico_imagen TEXT,
  lugar_turistico_video TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Tabla de Platos Típicos (Limpia)
CREATE TABLE public.platos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(150) NOT NULL,
  municipio_id BIGINT REFERENCES public.municipios(id) ON DELETE SET NULL,
  descripcion TEXT NOT NULL,
  ingredientes TEXT NOT NULL,
  preparacion TEXT NOT NULL,
  imagen_principal TEXT,
  imagen_preparacion TEXT,
  video_preparacion TEXT,
  destacado SMALLINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. Tabla de Administradores (Solo credenciales de acceso)
CREATE TABLE public.administradores (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL,
  usuario VARCHAR(50) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  rol VARCHAR(30) NOT NULL DEFAULT 'administrador',
  activo SMALLINT NOT NULL DEFAULT 1,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 4. Tabla de Configuración de Portada (Limpia lista para tus fotos)
CREATE TABLE public.configuracion_hero (
  id BIGINT PRIMARY KEY DEFAULT 1,
  banner_imagen TEXT,
  banner_titulo VARCHAR(200) NOT NULL DEFAULT 'Sabores de Cochabamba',
  banner_subtitulo VARCHAR(200) NOT NULL DEFAULT 'Tierra bendecida por su cocina y sus tradiciones',
  banner_descripcion TEXT,
  insignia_titulo VARCHAR(150) DEFAULT '',
  insignia_subtitulo VARCHAR(200) DEFAULT '',
  insignia_imagen TEXT DEFAULT '',
  insignia_descripcion TEXT DEFAULT '',
  insignia_plato_id BIGINT,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Habilitar Supabase Realtime
ALTER PUBLICATION supabase_realtime ADD TABLE public.configuracion_hero;
ALTER PUBLICATION supabase_realtime ADD TABLE public.platos;
ALTER PUBLICATION supabase_realtime ADD TABLE public.municipios;

